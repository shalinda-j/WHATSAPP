import mongoose, { Schema, Document } from 'mongoose';

export interface INLPCache extends Document {
    intentName: string;         // e.g., "auto_learn_123456"
    userUtterances: string[];   // Array of variations of the questions users ask
    aiResponse: string;         // The response generated by AI that we want to cache
    createdAt: Date;
    updatedAt: Date;
}

const NLPCacheSchema = new Schema(
    {
        intentName: { type: String, required: true, unique: true },
        userUtterances: [{ type: String, required: true }],
        aiResponse: { type: String, required: true },
    },
    { timestamps: true }
);

export default mongoose.model('NLPCache', NLPCacheSchema as any) as unknown as mongoose.Model<INLPCache>;
